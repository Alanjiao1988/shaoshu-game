  t("预览：新增军令背古诗", d.addT.includes("背古诗"));
  t("预览：调整数学口算", d.chgT.some(s=>s.startsWith("数学口算")&&/25/.test(s)));
  t("预览：停用单词打卡", d.offT.includes("单词打卡"));
  t("预览：新增锦囊/调整门槛", d.addP.some(s=>s.startsWith("去动物园"))&&d.chgP.some(s=>s.startsWith("一支新笔")));
